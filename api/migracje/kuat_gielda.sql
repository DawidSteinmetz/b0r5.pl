-- 1. Zmiany schematu ---------------------------------------------------------
-- 1a. Jeden towar może być notowany na wielu giełdach (wcześniej UNIQUE na towar_id).
--     KEY idx_instrumenty_towar zostaje jako indeks pod FK instrumenty_ibfk_2.
ALTER TABLE `instrumenty`
  ADD KEY `idx_instrumenty_towar` (`towar_id`),
  ADD UNIQUE KEY `uq_instrumenty_gielda_towar` (`gielda_id`,`towar_id`),
  DROP INDEX `uq_instrumenty_towar`;

-- 1b. Ceny z ułamkami (ruda 33 IC/t, akcje 543,44). Dotąd BIGINT zaokrąglał do całości.
