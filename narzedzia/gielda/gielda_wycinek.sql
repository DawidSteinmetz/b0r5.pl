-- ================= SCHEMAT =================

CREATE TABLE `mapa_planety` (
  `id` int UNSIGNED NOT NULL,
  `nazwa` varchar(160) NOT NULL,
  `region` tinyint UNSIGNED NOT NULL,
  `x` decimal(12,1) NOT NULL,
  `y` decimal(12,1) NOT NULL,
  `grawitacja` decimal(6,3) NOT NULL,
  `slonca` smallint UNSIGNED NOT NULL,
  `ksiezyce` smallint UNSIGNED NOT NULL,
  `doba` decimal(10,2) NOT NULL,
  `rok` decimal(10,2) NOT NULL,
  `srednica` decimal(12,2) NOT NULL,
  `poparcie_imperium_pct` decimal(5,2) DEFAULT NULL COMMENT 'Szacunkowe poparcie Imperium w procentach (model gry, 3 BBY)',
  `poparcie_rebelia_pct` decimal(5,2) DEFAULT NULL COMMENT 'Szacunkowe poparcie Rebelii w procentach (model gry, 3 BBY)',
  `poparcie_syndykat_pct` decimal(5,2) DEFAULT NULL COMMENT 'Szacunkowe poparcie Syndykatu w procentach (model gry, 3 BBY)',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_mapa_planety_nazwa` (`nazwa`),
  KEY `ix_mapa_planety_xy` (`x`,`y`)
);

CREATE TABLE `planety_gry` (
  `planeta_id` int UNSIGNED NOT NULL,
  `uklad_id` int UNSIGNED DEFAULT NULL,
  `typ_planety` enum('pustynna','lodowa','oceaniczna','lesna','wulkaniczna','gazowa','miasto','bagienna','skalista','pionowe_miasto') DEFAULT NULL,
  `urbanizacja` enum('brak','niska','wysoka') NOT NULL DEFAULT 'brak',
  `taksowka_kr_za_km` int UNSIGNED DEFAULT NULL,
  `kontrola_lotow` varchar(120) DEFAULT NULL,
  `zastrzezona` tinyint(1) NOT NULL DEFAULT '0',
  `opis` text,
  PRIMARY KEY (`planeta_id`),
  KEY `ix_planety_gry_uklad` (`uklad_id`),
  CONSTRAINT `planety_gry_ibfk_1` FOREIGN KEY (`planeta_id`) REFERENCES `mapa_planety` (`id`),
  CONSTRAINT `planety_gry_ibfk_2` FOREIGN KEY (`uklad_id`) REFERENCES `uklady_planetarne` (`id`)
);

CREATE TABLE `gielde` (
  `id` bigint UNSIGNED NOT NULL AUTO_INCREMENT,
  `kod` varchar(8) NOT NULL DEFAULT '',
  `planeta_id` int UNSIGNED NOT NULL,
  `nazwa` varchar(120) NOT NULL,
  `aktywna` tinyint(1) NOT NULL DEFAULT '1',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_gielde_nazwa` (`nazwa`),
  UNIQUE KEY `uq_gielde_kod` (`kod`),
  KEY `planeta_id` (`planeta_id`),
  CONSTRAINT `gielde_ibfk_1` FOREIGN KEY (`planeta_id`) REFERENCES `mapa_planety` (`id`)
);

CREATE TABLE `towary` (
  `id` bigint UNSIGNED NOT NULL AUTO_INCREMENT,
  `nazwa` varchar(160) NOT NULL,
  `kategoria` enum('paliwo','surowce','zywnosc','medycyna','technika','bron','luksus','przyprawy') NOT NULL,
  `masa_t_na_jednostke` decimal(12,4) NOT NULL DEFAULT '1.0000',
  `jednostka` varchar(20) NOT NULL DEFAULT 'szt',
  `cena_bazowa` bigint UNSIGNED NOT NULL DEFAULT '0',
  `kontrabanda` tinyint(1) NOT NULL DEFAULT '0',
  `opis` text,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_towary_nazwa` (`nazwa`)
);

CREATE TABLE `kategorie_towarow` (
  `id` bigint UNSIGNED NOT NULL AUTO_INCREMENT,
  `kod` varchar(40) NOT NULL,
  `nazwa` varchar(100) NOT NULL,
  `kategoria_nadrzedna_id` bigint UNSIGNED DEFAULT NULL,
  `opis` varchar(255) DEFAULT NULL,
  `kolejnosc` smallint NOT NULL DEFAULT '0',
  `aktywna` tinyint(1) NOT NULL DEFAULT '1',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_kategorie_towarow_kod` (`kod`),
  KEY `kategoria_nadrzedna_id` (`kategoria_nadrzedna_id`),
  CONSTRAINT `kategorie_towarow_ibfk_1` FOREIGN KEY (`kategoria_nadrzedna_id`) REFERENCES `kategorie_towarow` (`id`)
);

CREATE TABLE `towary_kategorie` (
  `towar_id` bigint UNSIGNED NOT NULL,
  `kategoria_id` bigint UNSIGNED NOT NULL,
  `glowna` tinyint(1) NOT NULL DEFAULT '0',
  PRIMARY KEY (`towar_id`,`kategoria_id`),
  KEY `ix_towary_kategorie_glowna` (`kategoria_id`,`glowna`),
  CONSTRAINT `towary_kategorie_ibfk_1` FOREIGN KEY (`towar_id`) REFERENCES `towary` (`id`),
  CONSTRAINT `towary_kategorie_ibfk_2` FOREIGN KEY (`kategoria_id`) REFERENCES `kategorie_towarow` (`id`)
);

CREATE TABLE `podmioty` (
  `id` bigint UNSIGNED NOT NULL AUTO_INCREMENT,
  `typ` varchar(12) NOT NULL,
  `nazwa` varchar(160) NOT NULL,
  `status` enum('aktywny','zawieszony','usuniety') NOT NULL DEFAULT 'aktywny',
  `utworzono` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_podmioty_id_typ` (`id`,`typ`),
  KEY `ix_podmioty_nazwa` (`nazwa`)
);

CREATE TABLE `firmy` (
  `podmiot_id` bigint UNSIGNED NOT NULL,
  `typ` varchar(12) NOT NULL DEFAULT 'firma',
  `profil` enum('transport','wydobycie','produkcja','finanse','komorka','agencja') NOT NULL,
  `kapital_zakladowy` bigint UNSIGNED NOT NULL DEFAULT '0',
  `skala` tinyint UNSIGNED NOT NULL DEFAULT '1',
  `opis` text,
  PRIMARY KEY (`podmiot_id`),
  KEY `podmiot_id` (`podmiot_id`,`typ`),
  CONSTRAINT `firmy_ibfk_1` FOREIGN KEY (`podmiot_id`,`typ`) REFERENCES `podmioty` (`id`, `typ`)
);

CREATE TABLE `instrumenty` (
  `id` bigint UNSIGNED NOT NULL AUTO_INCREMENT,
  `symbol` varchar(16) NOT NULL,
  `nazwa` varchar(160) NOT NULL,
  `rodzaj` enum('towar','spolka') NOT NULL,
  `kategoria` varchar(40) NOT NULL DEFAULT '',
  `jednostka` varchar(30) NOT NULL DEFAULT 'szt',
  `pochodzenie` varchar(80) DEFAULT NULL,
  `gielda_id` bigint UNSIGNED NOT NULL,
  `towar_id` bigint UNSIGNED DEFAULT NULL,
  `firma_id` bigint UNSIGNED DEFAULT NULL,
  `cena_bazowa` decimal(18,4) UNSIGNED NOT NULL,
  `zmiennosc` decimal(6,3) NOT NULL DEFAULT '1.000',
  `notowany` tinyint(1) NOT NULL DEFAULT '1',
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_instrumenty_symbol` (`symbol`),
  UNIQUE KEY `uq_instrumenty_firma` (`firma_id`),
  UNIQUE KEY `uq_instrumenty_gielda_towar` (`gielda_id`,`towar_id`),
  KEY `idx_instrumenty_towar` (`towar_id`),
  CONSTRAINT `instrumenty_ibfk_1` FOREIGN KEY (`gielda_id`) REFERENCES `gielde` (`id`),
  CONSTRAINT `instrumenty_ibfk_2` FOREIGN KEY (`towar_id`) REFERENCES `towary` (`id`),
  CONSTRAINT `instrumenty_ibfk_3` FOREIGN KEY (`firma_id`) REFERENCES `firmy` (`podmiot_id`)
);

CREATE TABLE `kursy_dzienne` (
  `instrument_id` bigint UNSIGNED NOT NULL,
  `data` date NOT NULL,
  `kurs` decimal(18,4) UNSIGNED NOT NULL,
  PRIMARY KEY (`instrument_id`,`data`),
  CONSTRAINT `kursy_dzienne_ibfk_1` FOREIGN KEY (`instrument_id`) REFERENCES `instrumenty` (`id`)
);

CREATE TABLE `gosp_towary` (
  `kod` varchar(40) NOT NULL,
  `towar_id` bigint UNSIGNED DEFAULT NULL,
  `nazwa` varchar(120) NOT NULL,
  `kategoria` varchar(40) NOT NULL,
  `ladownosc_t` int UNSIGNED NOT NULL COMMENT 'typowy ładunek jednego transportu',
  `klasa_transportu` varchar(80) NOT NULL,
  `zrodlo` varchar(80) NOT NULL DEFAULT 'wygenerowane',
  `cena_bazowa_kr_t` decimal(12,2) NOT NULL DEFAULT '100.00',
  PRIMARY KEY (`kod`),
  UNIQUE KEY `uq_gosp_towary_towar` (`towar_id`),
  CONSTRAINT `gosp_towary_ibfk_1` FOREIGN KEY (`towar_id`) REFERENCES `towary` (`id`)
);

CREATE TABLE `gosp_rynek` (
  `planeta` varchar(160) NOT NULL,
  `towar` varchar(40) NOT NULL,
  `obieg` varchar(30) NOT NULL DEFAULT 'oficjalny_hurt',
  `produkcja_t_doba` decimal(14,1) NOT NULL DEFAULT '0.0',
  `zuzycie_t_doba` decimal(14,1) NOT NULL DEFAULT '0.0',
  `cena_indeks` decimal(6,3) NOT NULL DEFAULT '1.000',
  `cena_kr_t` decimal(12,2) NOT NULL DEFAULT '0.00',
  `szczegolowosc` enum('obiekty','szacunek') NOT NULL DEFAULT 'szacunek',
  `zrodlo` varchar(80) NOT NULL DEFAULT 'wygenerowane',
  `uwagi` varchar(300) NOT NULL DEFAULT '',
  `zmieniono` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`planeta`,`towar`,`obieg`),
  KEY `ix_gosp_rynek_towar` (`towar`,`obieg`)
);

CREATE TABLE `ustawienia` (
  `klucz` varchar(80) NOT NULL,
  `wartosc` varchar(500) NOT NULL,
  `opis` varchar(255) DEFAULT NULL,
  PRIMARY KEY (`klucz`)
);

CREATE TABLE `schema_migracje` (
  `wersja` varchar(40) NOT NULL,
  `opis` varchar(255) NOT NULL,
  `zastosowano` timestamp NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`wersja`)
);

