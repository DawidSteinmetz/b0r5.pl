-- Zręby gospodarki galaktycznej i obiekty tła Kuat z liniami dostaw (wygenerowane skryptem).
--
-- Wookieepedia: durastal = żelazo + węgiel + karwanium, lommit, meleenium, neutronium, zersium. Lommit: Dorvalla, Elom,
-- Ord Thoden; meleenium (i doonium, dolowit, kammris): Wadi Raffa; zersium: Nag Ubdur; tibanna: Bespin. Kuat (Legends):
-- powierzchnia to ogrody i posiadłości, 3,6 mld mieszkańców, setki milionów robotników na pierścieniu, fabryki AT-AT.
-- Reszta (producenci rud, węgla, paliwa, żywności, elektroniki…) — wygenerowana (gosp_produkcja.zrodlo).
--
-- Szacunek: ISD 35 mln t, budowa 2 lata, 360 w budowie → ok. 12 mln t durastali na dobę (18 hut na pierścieniu,
-- ruda ×1,3 + węgiel i dodatki stopowe), podzespoły z 24 fabryk, żywność dla 300 mln mieszkańców pierścienia i połowy
-- potrzeb powierzchni. Linie dostaw: częstotliwość = ładowność / zużycie na dobę. Razem 90 obiektów,
-- 432 linii, ok. 287 dostaw na dobę do Kuat.
--
-- Import w phpMyAdmin; ponowny import czyści i wpisuje dane gospodarki od nowa.

USE hololink;
SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS gosp_towary (
  kod VARCHAR(40) NOT NULL PRIMARY KEY,
  nazwa VARCHAR(120) NOT NULL,
  kategoria VARCHAR(40) NOT NULL,
  ladownosc_t INT UNSIGNED NOT NULL COMMENT 'typowy ładunek jednego transportu',
  klasa_transportu VARCHAR(80) NOT NULL,
  zrodlo VARCHAR(80) NOT NULL DEFAULT 'wygenerowane'
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS gosp_produkcja (
  planeta VARCHAR(160) NOT NULL,
  towar VARCHAR(40) NOT NULL,
  wydajnosc_t_doba INT UNSIGNED NOT NULL,
  zrodlo VARCHAR(80) NOT NULL DEFAULT 'wygenerowane',
  PRIMARY KEY (planeta, towar),
  KEY ix_gosp_produkcja_towar (towar)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS gosp_obiekty (
  id INT UNSIGNED NOT NULL PRIMARY KEY,
  planeta VARCHAR(160) NOT NULL,
  nazwa VARCHAR(160) NOT NULL,
  rodzaj VARCHAR(40) NOT NULL,
  miejsce ENUM('powierzchnia','pierscien') NOT NULL,
  szer DECIMAL(8,3) NULL,
  dl DECIMAL(8,3) NULL,
  kat_deg DECIMAL(8,3) NULL COMMENT 'miejsce na pierścieniu orbitalnym',
  opis VARCHAR(300) NOT NULL DEFAULT '',
  KEY ix_gosp_obiekty_planeta (planeta)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS gosp_zuzycie (
  obiekt_id INT UNSIGNED NOT NULL,
  towar VARCHAR(40) NOT NULL,
  t_doba DECIMAL(14,1) NOT NULL,
  PRIMARY KEY (obiekt_id, towar)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS gosp_linie (
  id INT UNSIGNED NOT NULL PRIMARY KEY,
  obiekt_id INT UNSIGNED NOT NULL,
  towar VARCHAR(40) NOT NULL,
  producent VARCHAR(160) NOT NULL COMMENT 'planeta producenta',
  t_doba DECIMAL(14,1) NOT NULL,
  ladownosc_t INT UNSIGNED NOT NULL,
  klasa VARCHAR(80) NOT NULL,
  odstep_s INT UNSIGNED NOT NULL COMMENT 'co ile wylatuje kolejny transport',
  predkosc_au_h DECIMAL(5,2) NOT NULL,
  postoj_h DECIMAL(4,1) NOT NULL COMMENT 'załadunek / rozładunek',
  faza DECIMAL(5,4) NOT NULL,
  KEY ix_gosp_linie_obiekt (obiekt_id),
  KEY ix_gosp_linie_producent (producent)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

