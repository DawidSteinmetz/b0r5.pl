-- 7. Wartość dostaw na Kuat po bieżących kursach giełdy Kuat -------------------
CREATE OR REPLACE VIEW `v_kuat_dostawy_wartosc` AS
SELECT l.id AS linia_id, o.nazwa AS obiekt, o.rodzaj AS rodzaj_obiektu, l.towar AS kod_towaru,
       l.producent, l.t_doba, k.kurs AS kurs_kuat, ROUND(l.t_doba*k.kurs,2) AS wartosc_doba
FROM `gosp_linie` l
JOIN `gosp_obiekty` o ON o.id=l.obiekt_id AND o.planeta='Kuat'
JOIN `gosp_towary` gt ON gt.kod=l.towar
JOIN `instrumenty` i ON i.towar_id=gt.towar_id
JOIN `gielde` g ON g.id=i.gielda_id AND g.nazwa='Giełda Stoczniowa Kuat'
JOIN `kursy_dzienne` k ON k.instrument_id=i.id
 AND k.data=(SELECT MAX(x.data) FROM `kursy_dzienne` x WHERE x.instrument_id=i.id);

